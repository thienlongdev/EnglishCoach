-- Vocabulary Deck Catalog & System Content Ingestion

CREATE TABLE IF NOT EXISTS public.vocab_decks (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug character varying(100) NOT NULL UNIQUE,
    title character varying(255) NOT NULL,
    description text,
    category character varying(50) NOT NULL,
    theme_color character varying(50) NOT NULL DEFAULT 'emerald',
    icon character varying(50) NOT NULL DEFAULT 'book',
    total_words integer NOT NULL DEFAULT 0,
    is_system boolean NOT NULL DEFAULT true,
    sort_order integer NOT NULL DEFAULT 0,
    created_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.deck_dictionary_entries (
    deck_id bigint NOT NULL REFERENCES public.vocab_decks(id) ON DELETE CASCADE,
    dictionary_entry_id bigint NOT NULL REFERENCES public.dictionary_entries(id) ON DELETE CASCADE,
    sort_order integer NOT NULL DEFAULT 0,
    PRIMARY KEY (deck_id, dictionary_entry_id)
);

ALTER TABLE public.flashcards ADD COLUMN IF NOT EXISTS deck_id bigint REFERENCES public.vocab_decks(id);

CREATE INDEX IF NOT EXISTS idx_flashcards_user_deck ON public.flashcards (user_id, deck_id);
