    @Test void retriesReuseReceiptQuotaAndGpuResultAcrossBackendRestart(){
        var usage=mock(PremiumUsageService.class);when(usage.reserveUsage(anyLong(),anyString(),anyString(),anyBoolean())).thenReturn(10L);
        var listening=mock(ListeningServiceImpl.class);
        when(listening.persistVerifiedJob(any(),eq(1L),any())).thenReturn(ListeningMaterialDetailDto.builder().id(100L).build());
        var first=service(usage,listening);
        var job=first.create(1L,request());
        assertThat(first.create(1L,request()).id()).isEqualTo(job.id());
        verify(usage,times(1)).reserveUsage(anyLong(),anyString(),anyString(),anyBoolean());
        assertThatThrownBy(()->first.get(2L,job.id())).isInstanceOf(ResponseStatusException.class);
        assertThatThrownBy(()->first.cancel(2L,job.id())).isInstanceOf(ResponseStatusException.class);
        var restarted=service(usage,listening);
        var server=MockRestServiceServer.bindTo((RestTemplate)ReflectionTestUtils.getField(restarted,"gpu")).build();
        String engine=jdbc.queryForObject("SELECT engine_id::text FROM listening_youtube_jobs",String.class);
        server.expect(requestTo("http://gpu/api/v1/listening/jobs/"+engine)).andRespond(withSuccess("{\"status\":\"READY\"}",MediaType.APPLICATION_JSON));
        server.expect(requestTo("http://gpu/api/v1/listening/jobs/"+engine+"/result")).andRespond(withSuccess("{\"result\":{\"segments\":[]}}",MediaType.APPLICATION_JSON));
        restarted.tick();restarted.tick();
        assertThat(restarted.get(1L,job.id()).status()).isEqualTo("READY");
        assertThat(first.create(1L,request()).materialId()).isEqualTo(100L);
        verify(listening,times(1)).persistVerifiedJob(any(),eq(1L),any());verify(usage,times(1)).commitReservation(10L);
        server.verify();first.stop();restarted.stop();
    }
    @Test void cancellationReleasesQuotaAndNoLessonCanBePublished(){
        var usage=mock(PremiumUsageService.class);when(usage.reserveUsage(anyLong(),anyString(),anyString(),anyBoolean())).thenReturn(10L);
        var listening=mock(ListeningServiceImpl.class);var jobs=service(usage,listening);
        var job=jobs.create(1L,request());jobs.cancel(1L,job.id());jobs.cancel(1L,job.id());
        assertThat(jobs.get(1L,job.id()).status()).isEqualTo("CANCELLED");
        verify(usage,times(1)).releaseReservation(10L);verifyNoInteractions(listening);jobs.stop();
    }
    @Test void failedCommitPublishesNeitherReadyNorQuota(){
        var usage=mock(PremiumUsageService.class);when(usage.reserveUsage(anyLong(),anyString(),anyString(),anyBoolean())).thenReturn(10L);
        var listening=mock(ListeningServiceImpl.class);
        when(listening.persistVerifiedJob(any(),eq(1L),any())).thenAnswer(a -> {jdbc.update("INSERT INTO listening_materials(id,owner_user_id) VALUES(999,1)");throw new IllegalStateException("test crash");});
        var jobs=service(usage,listening);var job=jobs.create(1L,request());
        var server=MockRestServiceServer.bindTo((RestTemplate)ReflectionTestUtils.getField(jobs,"gpu")).build();
        server.expect(anything()).andRespond(withSuccess("{\"status\":\"READY\"}",MediaType.APPLICATION_JSON));
        server.expect(anything()).andRespond(withSuccess("{\"result\":{}}",MediaType.APPLICATION_JSON));
        jobs.tick();
        assertThat(jobs.get(1L,job.id()).status()).isEqualTo("FAILED");
        assertThat(jdbc.queryForObject("SELECT count(*) FROM listening_materials WHERE id=999",Integer.class)).isZero();
        verify(usage,never()).commitReservation(any());verify(usage).releaseReservation(10L);jobs.stop();
    }
