    @Test void longTranscriptHasExactLinksAndRollsBackAtomically(){
        var writer=new ListeningTranscriptWriter(jdbc,mapper);
        List<TranscriptSegment> lines=new ArrayList<>();
        for(int i=0;i<659;i++)lines.add(TranscriptSegment.builder().startTimeMs(i*2100).endTimeMs(i*2100+1800)
            .speakerName("Speaker").text("Sentence "+i).wordsJson("[{\"word\":\"a\",\"start\":null,\"end\":null}]").difficultyScore(1.0+i*.05).build());
        long started=System.nanoTime();
        tx.executeWithoutResult(s -> writer.write(100L,lines));
        System.out.println("LISTENING_BULK_BENCHMARK segments=659 exchanges=1 elapsedMs="+(System.nanoTime()-started)/1_000_000);
        assertThat(jdbc.queryForObject("SELECT count(*) FROM listening_exercises e JOIN transcript_segments s ON s.id=e.transcript_segment_id WHERE e.expected_answer=s.text AND e.listening_material_id=s.listening_material_id",Integer.class)).isEqualTo(659);
        assertThat(lines).allSatisfy(s -> assertThat(s.getId()).isPositive());
        tx.executeWithoutResult(s -> {writer.write(101L,lines);s.setRollbackOnly();});
        assertThat(jdbc.queryForObject("SELECT count(*) FROM transcript_segments WHERE listening_material_id=101",Integer.class)).isZero();
        assertThat(jdbc.queryForObject("SELECT count(*) FROM listening_exercises WHERE listening_material_id=101",Integer.class)).isZero();
    }
