// Echo Life Phase 4 — the server's economy table, derived from the vendored V3/V2 rules (never hand-typed numbers).
// Output: backend/src/main/resources/echo-life/economy.json. Re-run after the vendored V3 copy changes:
//   node scripts/build-echo-life-economy.mjs
// Unique rewards (15 missions, 14 side arcs, every story-choice option, 20 landmarks, 16 keepsakes) are read from V3's tables or
// measured by running V3's own function on a fresh game; prices come from V3's runtime catalogue; caps from its anti-exploit
// guards. The server grants only these amounts, once per learner, whatever a client reports.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const v3=p=>import(pathToFileURL(path.join(here,'../src/lib/echo-life/v3',p)).href);
const V3=await v3('game-core/index.mjs');
const out=path.join(here,'../../backend/src/main/resources/echo-life/economy.json');

const xpOf=s=>Object.fromEntries(Object.entries(s.progression.skills).map(([k,v])=>[k,v.xp]));
function measure(run){
  const s=V3.createGame('measure');const c0=s.progression.economy.credits,x0=xpOf(s);
  run(s);
  const xp={};for(const [k,v] of Object.entries(xpOf(s)))if(v>x0[k])xp[k]=v-x0[k];
  return {credits:s.progression.economy.credits-c0,xp};
}
const uniques={};
for(const q of V3.quests)uniques['mission:'+q.id]={credits:q.reward,xp:{[q.skill||'social']:35}};
for(const q of V3.SIDE_QUESTS)uniques['side:'+q.id]={credits:q.rewards.credits,xp:{[q.rewards.skill]:q.rewards.skillXp}};
for(const c of Object.values(V3.STORY_CHOICES))for(const o of c.options)uniques[`choice:${c.id}:${o.key}`]=measure(s=>V3.makeStoryChoice(s,c.id,o.key));
for(const l of V3.LANDMARKS)uniques['landmark:'+l.id]=measure(s=>{s.worldV3.exploration.discoveredLandmarks=s.worldV3.exploration.discoveredLandmarks.filter(x=>x!==l.id);s.worldV3.exploration.discoveredZones=s.worldV3.exploration.discoveredZones.filter(z=>z!==l.zone);V3.discoverZone(s,l.zone);});
for(const c of V3.COLLECTIBLES)uniques['relic:'+c.id]=measure(s=>V3.collectRelic(s,c.id));
const guards=V3.CATALOG.economy.antiExploitGuards;
const marketEvent=V3.WORLD_EVENTS.find(e=>e.id==='evt_market_produce_sale');
const shops={};
for(const [id,store] of Object.entries(V3.CATALOG.shops))shops[id]=Object.fromEntries(store.items.map(i=>[i.sku,{price:i.price,itemType:i.itemType,name:i.name,reqLevel:i.reqLevel||1,reqSkill:i.reqSkill||{}}]));
const table={
  version:1,
  source:'Echo Life V3 (Codex 23_OPEN_WORLD_GAMEPLAY_STORY_V3) vendored in frontend/src/lib/echo-life/v3 — generated by frontend/scripts/build-echo-life-economy.mjs',
  startingCredits:V3.CATALOG.economy.currency.startingBalance,
  maxBalance:V3.CATALOG.economy.currency.maxSafeBalance,
  // Repeatable earnings (shifts, minigames, events, deliveries, workshops) are bounded per report and per day, as V3's own guard.
  dailyActivityCredits:guards.maxDailyActivityCreditsCap,
  reportActivityCredits:150,
  dailyActivityXp:1600,
  reportActivityXp:70,
  resaleRatio:guards.resaleBaseRatio,
  marketSaleFactor:1-marketEvent.groceryDiscount,
  marketEvent:{days:marketEvent.days,startHour:marketEvent.startHour,endHour:marketEvent.endHour},
  skills:Object.keys(V3.createGame('x').progression.skills),
  skillThresholds:V3.CATALOG.skills.skillLevelThresholds,
  discount:Array.from({length:V3.CATALOG.skills.skillLevelThresholds.length},(_,i)=>{
    const level=i+1;
    const rate=V3.getStoreDiscountRate({progression:{skills:{business:{level}}}});
    return [level,rate];
  }).filter(([,rate],i,rows)=>rate>0 && rate!==rows[i-1]?.[1]).reverse(),
  missionRequires:Object.fromEntries(V3.quests.map(q=>[q.id,q.requires])),
  uniques,
  products:Object.fromEntries(Object.entries(V3.products).map(([k,v])=>[k,v.price])),
  shops,
};
fs.mkdirSync(path.dirname(out),{recursive:true});
fs.writeFileSync(out,JSON.stringify(table,null,1)+'\n');
console.log('economy.json',Object.keys(uniques).length,'unique rewards,',Object.values(shops).reduce((n,s)=>n+Object.keys(s).length,0),'shop items ->',path.relative(process.cwd(),out));
