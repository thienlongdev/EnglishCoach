// Bundle the vendored ESM graph for the backend. Its JS context has no filesystem access.
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const require = createRequire(import.meta.url);
const babel = require('next/dist/compiled/babel/bundle.js');
const root = fileURLToPath(new URL('../src/lib/echo-life/v3/',import.meta.url));
const out = fileURLToPath(new URL('../../backend/src/main/resources/echo-life/rules.js',import.meta.url));
const modules = new Map();
function add(id) {
  if (modules.has(id)) return;
  modules.set(id,'');
  const raw=fs.readFileSync(path.join(root,id),'utf8');
  if (id.endsWith('.json')) {modules.set(id,'module.exports='+raw+';');return;}
  const result=babel.core().transformSync(raw,{filename:id,babelrc:false,configFile:false,comments:false,plugins:[babel.pluginTransformModulesCommonjs()]}).code;
  modules.set(id,result.replace(/require\("([^"]+)"\)/g, (_,spec)=>{
    if (!spec.startsWith('.')) throw Error('Unexpected import '+spec);
    const dep=path.posix.join(path.posix.dirname(id),spec);
    add(dep);return 'require('+JSON.stringify(dep)+')';
  }));
}
add('game-core/index.mjs');
const jobs=fs.readFileSync(new URL('../src/lib/echo-life/game/jobs.json',import.meta.url),'utf8');
modules.set('host/jobs.json','module.exports='+jobs+';');
const table=[...modules].map(([id,code])=>JSON.stringify(id)+':function(module,exports,require){\n'+code+'\n}').join(',\n');
const adapter=fs.readFileSync(new URL('./echo-life-server-adapter.js',import.meta.url),'utf8');
fs.writeFileSync(out,'// Generated by build-echo-life-rules.mjs\nconst structuredClone=x=>JSON.parse(JSON.stringify(x));\nconst modules={'+table+'};\nconst cache=Object.create(null);\nfunction require(id){if(!cache[id]){const m=cache[id]={exports:{}};modules[id](m,m.exports,require);}return cache[id].exports;}\n'+adapter);
