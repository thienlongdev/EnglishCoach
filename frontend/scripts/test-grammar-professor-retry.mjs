import assert from 'node:assert/strict';
import {professorAction,restoreProfessorAction} from '../src/lib/grammar/professor-retry.ts';
const values=new Map();const storage={getItem:k=>values.get(k)??null,setItem:(k,v)=>values.set(k,v)};
let n=0;const id=()=>`00000000-0000-4000-8000-${String(++n).padStart(12,'0')}`;const now=1_000_000;
const act=(user,question,force=false,at=now)=>professorAction(storage,user,'verb-be',question,'',force,at,id);
const a=act('A','Question A');
assert.equal(act('A','Question A').id,a.id);
assert.notEqual(act('B','Question A').id,a.id);
act('A','Question B');assert.equal(act('A','Question A').id,a.id,'A→B→A keeps the prior logical action');
assert.equal(restoreProfessorAction(storage,'A','verb-be',now).question,'Question A');
assert.equal(restoreProfessorAction(storage,'A','verb-be',now).id,a.id,'a remount reads the persisted ID');
assert.equal(restoreProfessorAction(storage,'C','verb-be',now),null,'another account sees no previous action');
assert.notEqual(act('A','Question A',true).id,a.id,'explicit new action rotates the ID');
assert.equal(restoreProfessorAction(storage,'A','verb-be',now+86_400_001),null,'expired actions are not restored');
for(let i=0;i<20;i++)act('A',`Question ${i}`);
assert.equal(JSON.parse(values.get('ec_grammar_professor:v1:A')).length,12,'private buffer is bounded');
values.set('ec_grammar_professor:v1:A','{"unexpected":true}');assert.equal(restoreProfessorAction(storage,'A','verb-be',now),null);
const blocked={getItem(){throw Error('blocked');},setItem(){throw Error('blocked');}};
assert.ok(professorAction(blocked,'A','verb-be','Question','',false,now,id).id);
console.log('PASS Professor retry identity, owner isolation, reload, explicit restart, expiry, bounds and blocked-storage behavior');
