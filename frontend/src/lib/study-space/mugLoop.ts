const mix = (a: number, b: number, t: number) => a + (b - a) * t;
const vector = (a: Vector, b: Vector, t: number): Vector =>
  [mix(a[0], b[0], t), mix(a[1], b[1], t), mix(a[2], b[2], t)];

export function mugLoopAtScale(scale: number) {
  const index = samples.findIndex(s => s.scale >= scale);
  if (index < 0 || scale < samples[0].scale) return null;
  const b = samples[index], a = samples[Math.max(0, index - 1)];
  const t = a === b ? 1 : (scale - a.scale) / (b.scale - a.scale);
  const joints = t === 1 ? b.joints : a.joints.map((digit, i): Finger => {
    const next = b.joints[i];
    return [mix(digit[0], next[0], t), mix(digit[1], next[1], t), mix(digit[2], next[2], t),
      mix(digit[3], next[3], t), mix(digit[4], next[4], t)];
  });
  return { opening: vector(a.opening, b.opening, t), wristOffset: vector(a.wristOffset, b.wristOffset, t),
    fingers: [-.02556, .13026, -.99115] as Vector, palm: [-.884235, -.465463, -.038369] as Vector, joints };
}
