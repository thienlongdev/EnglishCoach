// Echo Anywhere build (no dependencies). Usage:
//   node build.mjs                      -> dist/unpacked (dev id, production site) + dist/store/*.zip (Chrome, Edge)
//   node build.mjs --site https://englishcoach.io.vn:18443 --out <dir>   -> one unpacked test build (dev id)
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const args = Object.fromEntries(process.argv.slice(2).reduce((acc, a, i, all) => (a.startsWith('--') ? [...acc, [a.slice(2), all[i + 1]]] : acc), []));
const SITE = (args.site || 'https://englishcoach.io.vn').replace(/\/+$/, '');
const site = new URL(SITE);
if (site.protocol !== 'https:') throw new Error('site must be https');
const base = JSON.parse(fs.readFileSync(path.join(here, 'manifest.base.json'), 'utf8'));
const key = JSON.parse(fs.readFileSync(path.join(here, 'dev-key.public.json'), 'utf8'));
const VERSION = base.version;

function manifest({ withKey, grant }) {
  const pattern = `${site.protocol}//${site.hostname}`; // match patterns carry no port
  const m = JSON.parse(JSON.stringify(base).replaceAll('__SITE__', pattern));
  if (withKey) m.key = key.key;
  if (grant) m.host_permissions.push(...grant.split(',').map((h) => `https://${h}/*`)); // TEST ONLY: as if the learner granted these sites
  return m;
}

function files(dir, rel = '') {
  return fs.readdirSync(path.join(dir, rel), { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? files(dir, path.join(rel, e.name)) : [path.join(rel, e.name).split(path.sep).join('/')]);
}

function assemble(outDir, opts) {
  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });
  const src = path.join(here, 'src');
  for (const f of files(src)) {
    const to = path.join(outDir, f);
    fs.mkdirSync(path.dirname(to), { recursive: true });
    if (f === 'content.js' && opts.test) fs.writeFileSync(to, fs.readFileSync(path.join(src, f), 'utf8').replace("const SHADOW_MODE = 'closed'", "const SHADOW_MODE = 'open'"));
    else if (f === 'config.js') fs.writeFileSync(to, `// Generated by build.mjs\nexport const SITE = ${JSON.stringify(SITE)};\nexport const VERSION = ${JSON.stringify(VERSION)};\n`);
    else fs.copyFileSync(path.join(src, f), to);
  }
  fs.writeFileSync(path.join(outDir, 'manifest.json'), `${JSON.stringify(manifest(opts), null, 2)}\n`);
  // guard: no remote code, no markup sinks, no eval in shipped scripts
  for (const f of files(outDir).filter((x) => x.endsWith('.js'))) {
    const s = fs.readFileSync(path.join(outDir, f), 'utf8');
    for (const bad of [/\.innerHTML\s*=/, /insertAdjacentHTML/, /document\.write/, /\beval\s*\(/, /new Function\s*\(/, /<script[^>]+src=["']https?:/i, /import\s*\(\s*['"]https?:/]) {
      if (bad.test(s)) throw new Error(`forbidden pattern ${bad} in ${f}`);
    }
  }
  return outDir;
}

// ---------------------------------------------------------------- minimal ZIP (deflate) writer
const CRC = new Uint32Array(256).map((_, n) => { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; return c >>> 0; });
const crc32 = (buf) => { let c = 0xffffffff; for (const b of buf) c = CRC[(c ^ b) & 0xff] ^ (c >>> 8); return (c ^ 0xffffffff) >>> 0; };
function zip(dir, outFile) {
  const entries = files(dir).sort();
  const chunks = [], central = [];
  let offset = 0;
  const dosTime = 0, dosDate = ((2026 - 1980) << 9) | (11 << 5) | 15; // fixed date: reproducible archives
  for (const name of entries) {
    const data = fs.readFileSync(path.join(dir, name));
    const comp = zlib.deflateRawSync(data, { level: 9 });
    const nameBuf = Buffer.from(name, 'utf8');
    const crc = crc32(data);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0); local.writeUInt16LE(20, 4); local.writeUInt16LE(0x0800, 6); local.writeUInt16LE(8, 8);
    local.writeUInt16LE(dosTime, 10); local.writeUInt16LE(dosDate, 12); local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(comp.length, 18); local.writeUInt32LE(data.length, 22); local.writeUInt16LE(nameBuf.length, 26); local.writeUInt16LE(0, 28);
    chunks.push(local, nameBuf, comp);
    const cd = Buffer.alloc(46);
    cd.writeUInt32LE(0x02014b50, 0); cd.writeUInt16LE(20, 4); cd.writeUInt16LE(20, 6); cd.writeUInt16LE(0x0800, 8); cd.writeUInt16LE(8, 10);
    cd.writeUInt16LE(dosTime, 12); cd.writeUInt16LE(dosDate, 14); cd.writeUInt32LE(crc, 16); cd.writeUInt32LE(comp.length, 20);
    cd.writeUInt32LE(data.length, 24); cd.writeUInt16LE(nameBuf.length, 28); cd.writeUInt32LE(offset, 42);
    central.push(cd, nameBuf);
    offset += 30 + nameBuf.length + comp.length;
  }
  const cdBuf = Buffer.concat(central);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(entries.length, 8); end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(cdBuf.length, 12); end.writeUInt32LE(offset, 16);
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, Buffer.concat([...chunks, cdBuf, end]));
  return outFile;
}

if (Object.hasOwn(args, 'chrome-only')) {
  if (args.out || args.site || args.grant) throw new Error('The Chrome release uses only the production origin and permissions.');
  const dist = path.join(here, 'dist');
  fs.mkdirSync(dist, { recursive: true });
  const staging = fs.mkdtempSync(path.join(dist, '.chrome-release-'));
  try {
    assemble(staging, { withKey: false });
    const out = zip(staging, path.join(dist, 'store', `echo-anywhere-chrome-${VERSION}.zip`));
    console.log(out, fs.statSync(out).size, 'bytes');
  } finally {
    fs.rmSync(staging, { recursive: true, force: true });
  }
} else if (args.out) {
  console.log(`test build -> ${assemble(path.resolve(args.out), { withKey: true, test: true, grant: args.grant })} (site ${SITE}, id ${key.id})`);
} else {
  const dist = path.join(here, 'dist');
  const unpacked = assemble(path.join(dist, 'unpacked'), { withKey: true });
  const storeDir = assemble(path.join(dist, '.store-tmp'), { withKey: false });
  const chrome = zip(storeDir, path.join(dist, 'store', `echo-anywhere-chrome-${VERSION}.zip`));
  const edge = zip(storeDir, path.join(dist, 'store', `echo-anywhere-edge-${VERSION}.zip`));
  const dev = zip(unpacked, path.join(dist, 'store', `echo-anywhere-dev-unpacked-${VERSION}.zip`));
  fs.rmSync(storeDir, { recursive: true, force: true });
  for (const f of [chrome, edge, dev]) console.log(`${path.relative(here, f)}  ${fs.statSync(f).size} bytes`);
  console.log(`unpacked dev build: ${path.relative(here, unpacked)} (id ${key.id})`);
}
