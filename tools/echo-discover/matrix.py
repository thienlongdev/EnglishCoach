"""Regenerate the release route inventory from scoped Git paths. No recursive filesystem walk."""
import argparse
import itertools
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'docs/echo-discover/ROUTES.md'
APP = 'frontend/src/app/'
PUBLIC = {'/', '/echo-anywhere', '/huong-dan', '/huong-dan/hoc-tu-trong-ngu-canh', '/huong-dan/nghe-chep-chinh-ta'}
AUTH = {'/login', '/register', '/verify-email', '/reset-password', '/forgot-password', '/echo-anywhere/connect'}


def paths(*patterns):
    command = ['git', 'ls-files', '--cached', '--others', '--exclude-standard', '--', *patterns, ':!docs/AGENTS_CODEX.md']
    return sorted(set(subprocess.check_output(command, cwd=ROOT, encoding='utf-8').splitlines()))


def family(url):
    if url in PUBLIC:
        return 'Public'
    if url in AUTH:
        return 'Account entry'
    if url.startswith('/api/'):
        return 'API'
    if url.startswith('/admin/'):
        return 'Admin'
    if 'preview' in url or '/dev/' in url:
        return 'Preview'
    if url.startswith(('/exams/', '/games/', '/speaking/arena', '/listening/')) and ('[' in url or url.startswith(('/games/', '/speaking/arena'))):
        return 'Practice / competition'
    if url in {'/premium', '/community'}:
        return 'Review'
    return 'Workspace'


def mapping_paths(args, constants):
    # Java shorthand, value=, path=, aliases in braces, and BASE + suffix.
    token = r'(?:"[^"]*"|[A-Z_]+\s*\+\s*"[^"]*")'
    m = re.search(r'(?:^\s*|\b(?:value|path)\s*=\s*)(' + token + r'|\{[^}]*\})', args)
    if not m:
        return ['']
    result = []
    for prefix, suffix in re.findall(r'(?:([A-Z_]+)\s*\+\s*)?"([^"]*)"', m[1]):
        result.append(constants[prefix] + suffix if prefix else suffix)
    return result or ['']


def backend():
    found = set()
    annotation = re.compile(r'@(Get|Post|Put|Patch|Delete|Request)Mapping\b\s*(?:\(([^)]*)\))?')
    for filename in paths('backend/src/main/java/**/*.java'):
        source = (ROOT / filename).read_text(encoding='utf-8-sig')
        if not re.search(r'@(RestController|Controller)\b', source):
            continue
        source = re.sub(r'/\*.*?\*/', '', source, flags=re.S)
        source = re.sub(r'^\s*//[^\n]*', '', source, flags=re.M)
        declaration = re.search(r'\bclass\s+\w+', source)
        if not declaration:
            continue
        constants = dict(re.findall(r'\bString\s+([A-Z_]+)\s*=\s*"([^"]*)"', source))
        base = re.search(r'@RequestMapping\s*\(([^)]*)\)', source[:declaration.start()])
        roots = mapping_paths(base[1], constants) if base else ['']
        for method, args in annotation.findall(source[declaration.end():]):
            verbs = [method.upper()] if method != 'Request' else re.findall(r'RequestMethod\.(\w+)', args) or ['ANY']
            for verb, root, leaf in itertools.product(verbs, roots, mapping_paths(args, constants)):
                url = '/' + '/'.join(s.strip('/') for s in [root, leaf] if s.strip('/'))
                found.add((url, verb, filename.split('/')[-1]))
    return sorted(found)


def render():
    rows = []
    for filename in paths(APP + '*'):
        if not filename.endswith(('/page.tsx', '/route.ts')):
            continue
        url = re.sub(r'/\([^/]+\)', '', '/' + filename[len(APP):].rsplit('/', 1)[0]) if '/' in filename[len(APP):] else '/'
        rows.append((url, family(url), filename[len(APP):]))
    routes = backend()
    lines = ['# Echo Discover route inventory', '',
             f'{len(rows)} App Router page/handler templates and {len(routes)} method/path/controller declarations in Spring source. Group folders do not affect the URL. Dynamic IDs below are templates. Generated by `python tools/echo-discover/matrix.py`.', '',
             '| Policy | Guest HTTP and access | Index, canonical, sitemap, schema | Rendering, language, performance and links |',
             '|---|---|---|---|',
             '| Public | 200 anonymous | Index on apex only, one HTTPS self canonical, included. WebSite on home and BreadcrumbList on guide pages. | Nonce SSR in Vietnamese. Landing has a lazy WebGL scene, extension has an interactive demo, guides render text and native controls. Home footer → guides and extension, guide hub ↔ lessons, vocabulary lesson ↔ extension. |',
             '| Account entry | 200 form or session-dependent transition, tokens checked by owning service | Noindex, no canonical or sitemap | Dynamic HTML, Vietnamese default, UI locale where supported. Linked by login, recovery, verification or extension flows. |',
             '| Workspace | A guest may receive a 200 application shell. Private data requires authorization at the API. Missing IDs can yield a protected shell while its API returns 401/404. | Noindex, no canonical, sitemap or schema | Per-request shell, hydrated tools, vi-first with account preference where supported, reached from workspace navigation. |',
             '| Practice / competition | 200 shell or guard, server validates owner, mode or attempt before returning personal data or recording a score. | Noindex, no canonical, sitemap or schema | Interactive runtime, heavier game/skill code, reached from the owning module. |',
             '| Admin | Admin shell and MFA gate, role/step-up enforced by backend | Noindex and /admin/ disallow, no canonical or sitemap | Dynamic operator UI reached by admin navigation. |',
             '| Review | Public feed or pricing with account-dependent controls | Noindex pending separate editorial/privacy review, no canonical or sitemap | Mixed server/client product UI, linked by footer and workspace. |',
             '| Preview | Development UI. Deployed Nginx returns 404 on landing-preview and shadowing dev descendants, CBT previews have production app guards. | Excluded, no canonical or sitemap | Dev fixture or visual QA. No public navigation. |',
             '| API | Method, auth, role and resource dependent. Security rules are in WebSecurityConfig and controllers. | Disallow /api/ and omit every service, no page schema | Data or action, consumed by application code, no editorial language or links. |', '',
             '| Template | Policy | Source under frontend/src/app |','|---|---|---|']
    lines.extend(f'| `{u}` | {f} | `{p}` |' for u, f, p in sorted(rows))
    lines.extend(['', '## Infrastructure and other URL states', '',
                  'Native metadata resources are /robots.txt, /sitemap.xml and /manifest.webmanifest. Static assets, security.txt, icons, audio, WebSocket upgrades and /_next resources are outside the editorial inventory. The two XML/text discovery resources return host-specific responses. Preview hosts get no indexable page and an empty sitemap. Unmatched public paths return 404. Known /?tab= module aliases use the existing 307 and preserve the other parameters. The landing alias and attribution parameters canonicalize to the clean page. HTTP apex and www variants redirect directly to HTTPS apex at Nginx.', '',
                  'Edge exceptions from deploy/nginx/default.conf include /.well-known/acme-challenge/ (certificate validation), /.well-known/security.txt (public security contact), /ws-card-blast (socket upgrade), /api/csp-report (report receiver), /api/dictionary, /api/translate and /api/tts (service calls). None is an indexable editorial page. Direct /api/v1/auth/login, /refresh, /session/refresh, /session/exchange, /google/exchange and /google/link under the same auth prefix are refused by Nginx. /api/v1/real-mic-pack/:path* is a development-only rewrite. /assets/, /_next/static/, /vendor/listening-translator/ and /vendor/study-physics/ deliver assets; their cache rules do not apply to private page HTML.', '',
                  '## Backend API declarations', '',
                  'All declarations inherit the API classification above. Paths are extracted from Spring mapping annotations, including class prefixes and array aliases. These are source declarations, not claims that each verb was exercised. The BFF catch-all and direct Nginx forwarding have different access paths. External PC AI/MDD services and actuator endpoints are internal infrastructure and have no public page policy.', '', '```text'])
    lines.extend(f'{verb:6} {url}  {controller}' for url, verb, controller in routes)
    return '\n'.join(lines + ['```', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    options = parser.parse_args()
    content = render()
    if options.check:
        if OUT.read_text(encoding='utf-8') != content:
            raise SystemExit('Route inventory drift. Review publication policy, then regenerate.')
    else:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(content, encoding='utf-8', newline='\n')
